const fs = require('fs');
const {pathToFileURL}=require('url');
const wait=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
 const tabs=await fetch('http://127.0.0.1:9333/json').then(r=>r.json());
 const tab=tabs.find(t=>t.type==='page');
 const socket=new WebSocket(tab.webSocketDebuggerUrl);
 await new Promise((resolve,reject)=>{socket.onopen=resolve;socket.onerror=reject;});
 let id=0;const pending=new Map();const errors=[];
 socket.onmessage=({data})=>{const value=JSON.parse(data);if(value.id){const task=pending.get(value.id);pending.delete(value.id);if(value.error)task.reject(Error(value.error.message));else task.resolve(value.result);}else if(value.method==='Runtime.exceptionThrown')errors.push(value.params.exceptionDetails.text);};
 const call=(method,params={})=>new Promise((resolve,reject)=>{pending.set(++id,{resolve,reject});socket.send(JSON.stringify({id,method,params}));});
 const evaluate=async expression=>{const r=await call('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw Error(JSON.stringify(r.exceptionDetails));return r.result.value;};
 const assert=(value,message)=>{if(!value)throw Error(message);console.log('PASS '+message);};
 await call('Runtime.enable');await call('Page.enable');
 await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
 await call('Page.navigate',{url:pathToFileURL(process.cwd()+'/index.html').href});
 await wait(2800);
 const report=await evaluate(`({title:document.title,width:innerWidth,scrollWidth:document.documentElement.scrollWidth,headings:document.querySelectorAll('.scroll-heading').length,words:document.querySelectorAll('h1 .word').length})`);
 console.log(JSON.stringify(report));
 assert(report.scrollWidth<=report.width,'desktop has no horizontal overflow');
 assert(report.headings>=6&&report.words>=4,'hero and section headings split into words');
 const capture=async name=>{const r=await call('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});fs.mkdirSync('previews',{recursive:true});fs.writeFileSync('previews/'+name+'.png',Buffer.from(r.data,'base64'));};
 await capture('desktop');
 await evaluate(`document.getElementById('services').scrollIntoView({behavior:'instant',block:'end'})`);await wait(400);
 const opacityBefore=await evaluate(`getComputedStyle(document.querySelector('#about h2 .word')).opacity`);
 await evaluate(`(()=>{const h=document.querySelector('#about h2');scrollTo({top:scrollY+h.getBoundingClientRect().top-innerHeight*.62,behavior:'instant'})})()`);await wait(700);
 const opacityAfter=await evaluate(`getComputedStyle(document.querySelector('#about h2 .word')).opacity`);
 assert(Number(opacityAfter)>Number(opacityBefore),'heading words reveal as scroll position advances');
 await capture('scroll-reveal');
 await evaluate(`document.querySelector('.assistant-toggle').click()`);
 assert(await evaluate(`!document.getElementById('chat').hidden`),'assistant opens');
 await evaluate(`document.querySelector('.chat-close').click(); document.querySelector('#team details').open=true`);
 assert(await evaluate(`document.querySelector('#team details').open`),'full company information expands');
 assert(await evaluate(`document.querySelectorAll('.project-gallery img').length===49`),'all 49 original gallery photographs retained');
 await evaluate(`document.querySelector('.project-gallery a').click()`);
 assert(await evaluate(`document.querySelector('.gallery-viewer').open`),'gallery viewer opens');
 await evaluate(`document.querySelector('.viewer-next').click()`);
 assert(await evaluate(`document.querySelector('.viewer-counter').textContent.includes('02 / 49')`),'gallery next control updates the photograph');
 await evaluate(`document.querySelector('.viewer-close').click()`);
 await wait(100);
 assert(await evaluate(`!document.querySelector('.gallery-viewer').open && document.body.style.overflow===''`),'closing viewer restores page scrolling');
 await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
 await evaluate(`scrollTo({top:0,behavior:'instant'})`);await wait(500);
 assert(await evaluate(`document.documentElement.scrollWidth<=innerWidth`),'phone has no horizontal overflow');
 await evaluate(`document.querySelector('.menu').click()`);
 assert(await evaluate(`document.querySelector('.menu').getAttribute('aria-expanded')==='true' && getComputedStyle(document.getElementById('nav-links')).display==='flex'`),'mobile navigation opens');
 await evaluate(`document.querySelector('.menu').click()`);await capture('mobile');
 await call('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]});await wait(100);
 assert(await evaluate(`!document.documentElement.classList.contains('motion-active')&&[...document.querySelectorAll('.word')].every(w=>getComputedStyle(w).opacity==='1')`),'reduced motion displays every word without animation');
 assert(errors.length===0,'no browser JavaScript exceptions');
 await call('Browser.close');socket.close();
 console.log('Browser checks complete.');
})().catch(e=>{console.error(e);process.exitCode=1;});
